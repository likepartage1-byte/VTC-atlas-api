/// Helper function — identical pattern to driver-app getTr()
String tr(String key, String lang) {
  final validLang = ['ar', 'fr', 'en', 'es'].contains(lang) ? lang : 'fr';
  return kPassengerTranslations[validLang]?[key] ??
      kPassengerTranslations['fr']?[key] ??
      key;
}

/// Returns true when language is RTL (Arabic)
bool isRTL(String lang) => lang == 'ar';
